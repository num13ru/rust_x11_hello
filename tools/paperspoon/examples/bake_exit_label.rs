//! Bake PaperPad's local Exit label from the pinned IBM Plex Mono asset.

use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;
use std::process::Command;
use std::sync::Arc;

use cosmic_text::{
    Attrs, Buffer, Color, Fallback, Family, FontSystem, Metrics, Shaping, SwashCache, Weight, Wrap,
    fontdb,
};
use unicode_script::Script;

const LABEL: &str = "EXIT";
const FAMILY: &str = "IBM Plex Mono";
const FONT_SIZE: f32 = 48.0;
const LINE_HEIGHT: f32 = 56.0;
const THRESHOLD: u8 = 128;
const CANVAS_WIDTH: usize = 256;
const CANVAS_HEIGHT: usize = 72;
const FONT_BYTES: &[u8] = include_bytes!("../assets/fonts/IBMPlexMono-Medium.ttf");

#[derive(Debug)]
struct NoFallback;

impl Fallback for NoFallback {
    fn common_fallback(&self) -> &[&'static str] {
        &[]
    }

    fn forbidden_fallback(&self) -> &[&'static str] {
        &[]
    }

    fn script_fallback(&self, _script: Script, _locale: &str) -> &[&'static str] {
        &[]
    }
}

fn main() -> Result<(), Box<dyn Error>> {
    let output = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(".cache/typography-spike/exit-label-ibm-plex-mono-48.rs"));
    if let Some(parent) = output
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
    {
        fs::create_dir_all(parent)?;
    }

    let mut database = fontdb::Database::new();
    let ids = database.load_font_source(fontdb::Source::Binary(Arc::new(FONT_BYTES.to_vec())));
    if ids.is_empty()
        || !ids.iter().any(|id| {
            database
                .face(*id)
                .is_some_and(|face| face.families.iter().any(|(name, _)| name == FAMILY))
        })
    {
        return Err("pinned IBM Plex Mono family was not loaded".into());
    }
    database.set_monospace_family(FAMILY);
    let mut font_system =
        FontSystem::new_with_locale_and_db_and_fallback("en-US".to_string(), database, NoFallback);
    let mut cache = SwashCache::new();
    let mut buffer = Buffer::new(&mut font_system, Metrics::new(FONT_SIZE, LINE_HEIGHT));
    let mut coverage = vec![0_u8; CANVAS_WIDTH * CANVAS_HEIGHT];
    {
        let mut buffer = buffer.borrow_with(&mut font_system);
        buffer.set_size(Some(CANVAS_WIDTH as f32), Some(CANVAS_HEIGHT as f32));
        buffer.set_wrap(Wrap::None);
        buffer.set_text(
            LABEL,
            &Attrs::new()
                .family(Family::Name(FAMILY))
                .weight(Weight::MEDIUM),
            Shaping::Advanced,
            None,
        );
        let run = buffer
            .layout_runs()
            .next()
            .ok_or("font engine produced no Exit label layout")?;
        if run.glyphs.len() != LABEL.chars().count()
            || run.glyphs.iter().any(|glyph| glyph.glyph_id == 0)
        {
            return Err("Exit label did not resolve to four pinned glyphs".into());
        }
        buffer.draw(
            &mut cache,
            Color::rgb(0, 0, 0),
            |x, y, width, height, color| {
                for offset_y in 0..height {
                    let Some(target_y) = y.checked_add_unsigned(offset_y) else {
                        continue;
                    };
                    let Ok(target_y) = usize::try_from(target_y) else {
                        continue;
                    };
                    if target_y >= CANVAS_HEIGHT {
                        continue;
                    }
                    for offset_x in 0..width {
                        let Some(target_x) = x.checked_add_unsigned(offset_x) else {
                            continue;
                        };
                        let Ok(target_x) = usize::try_from(target_x) else {
                            continue;
                        };
                        if target_x >= CANVAS_WIDTH {
                            continue;
                        }
                        let index = target_y * CANVAS_WIDTH + target_x;
                        coverage[index] = coverage[index].max(color.a());
                    }
                }
            },
        );
    }

    let (left, top, right, bottom) = threshold_bounds(&coverage)
        .ok_or("thresholded Exit label produced no foreground pixels")?;
    let width = right - left;
    let height = bottom - top;
    let stride = width.div_ceil(8);
    let mut bits = vec![0_u8; stride * height];
    for y in 0..height {
        for x in 0..width {
            if coverage[(top + y) * CANVAS_WIDTH + left + x] >= THRESHOLD {
                bits[y * stride + x / 8] |= 0x80 >> (x % 8);
            }
        }
    }

    let mut source = String::new();
    writeln!(source, "//! Baked PaperPad-local Exit label.")?;
    writeln!(source, "//!")?;
    writeln!(
        source,
        "//! Generated by tools/paperspoon/examples/bake_exit_label.rs from"
    )?;
    writeln!(
        source,
        "//! IBMPlexMono-Medium.ttf at 48 px with threshold 128."
    )?;
    writeln!(
        source,
        "//! Font SHA-256: 98fbd727aae340b236955879dabed4d991aac9e8e90b3b2a67ce4a59221cc97c."
    )?;
    writeln!(source)?;
    writeln!(
        source,
        "pub(super) const EXIT_LABEL_WIDTH: usize = {width};"
    )?;
    writeln!(
        source,
        "pub(super) const EXIT_LABEL_HEIGHT: usize = {height};"
    )?;
    writeln!(
        source,
        "pub(super) const EXIT_LABEL_STRIDE: usize = {stride};"
    )?;
    writeln!(
        source,
        "pub(super) const EXIT_LABEL_BITS: [u8; {}] = [",
        bits.len()
    )?;
    for row in bits.chunks(stride) {
        write!(source, "    ")?;
        for byte in row {
            write!(source, "0x{byte:02x}, ")?;
        }
        writeln!(source)?;
    }
    writeln!(source, "];")?;
    fs::write(&output, source)?;
    let rustfmt = Command::new("rustfmt")
        .arg("--edition")
        .arg("2024")
        .arg(&output)
        .status()?;
    if !rustfmt.success() {
        return Err("rustfmt failed to format the baked Rust asset".into());
    }

    let preview = output.with_extension("pbm");
    let mut pbm = format!("P4\n{width} {height}\n").into_bytes();
    pbm.extend_from_slice(&bits);
    fs::write(&preview, pbm)?;
    eprintln!(
        "baked {LABEL:?} as {width}x{height}, stride {stride}, {} bytes -> {}",
        bits.len(),
        output.display()
    );
    Ok(())
}

fn threshold_bounds(coverage: &[u8]) -> Option<(usize, usize, usize, usize)> {
    let mut left = CANVAS_WIDTH;
    let mut top = CANVAS_HEIGHT;
    let mut right = 0_usize;
    let mut bottom = 0_usize;
    let mut found = false;
    for y in 0..CANVAS_HEIGHT {
        for x in 0..CANVAS_WIDTH {
            if coverage[y * CANVAS_WIDTH + x] < THRESHOLD {
                continue;
            }
            found = true;
            left = left.min(x);
            top = top.min(y);
            right = right.max(x + 1);
            bottom = bottom.max(y + 1);
        }
    }
    found.then_some((left, top, right, bottom))
}
